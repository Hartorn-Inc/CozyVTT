import { describe, it, expect } from 'vitest';
import { isValidDiceExpression } from '../diceExpression';

describe('isValidDiceExpression', () => {
  describe('valid dice expressions and shorthands', () => {
    const validCases: string[] = [
      '1d20',
      'adv',
      'dis',
      'ADV',
      'Dis',
      'd%',
      '1d%',
      '2d%',
      '3D%',
      'd20',
      'd6',
      '4d6kh3',
      '4d6dl1',
      '2d20kl1',
      '1d20+5',
      '1D20',
      '2D6',
      '2d6+3',
      '3d10-2',
      '2d6+1d4+3',
      '1d12*2',
      '10d6',
      '1d6+1d8',
      '5',
      '1d20 + 5',
      '  2d6  +  3  ',
      '(2 + 3) * 4',
      '((1d20 + 5) * 2)',
      '(1d20)',
      '1d20++5',
      '1d20+-5',
      '100d1',
      'd1000',
      '1d20+9999',
    ];

    it.each(validCases)('accepts valid expression: %j', (expr) => {
      expect(isValidDiceExpression(expr)).toBe(true);
    });
  });

  describe('malformed syntax and invalid edge cases', () => {
    const invalidCases: string[] = [
      '',
      '   ',
      '2d6+',
      '+2d6',
      '///',
      '2d6*',
      '/2d6',
      '1d6/',
      '/0',
      '1d6//0',
      '1d6/*2',
      '+',
      '-',
      '*2',
      '/2',
      '2d6+-',
      '()',
      '(   )',
      '(1d20+5',
      '1d20+5)',
      '1d20**5',
      '4d6kh5',
      '4d6kh0',
      '4d6kl5',
      '4d6kl0',
      '4d6dh4',
      '4d6dh5',
      '4d6dh0',
      '2d6dl2',
      '4d6dl4',
      '4d6dl5',
      '4d6dl0',
      '1d6dl1',
      '1d6dh1',
      '2d6kh',
      '4d6dl',
      '101d20',
      '50d6+51d6',
      '1d1001',
      '1d0',
      'd0',
      '1d20+10000',
      '10000',
      '-10000',
      '1d6/0',
      '10/0',
      '0/0',
      '4d6/0',
      '1d20/0',
      '2d20kh1/0',
      '10/2/0',
      '2+1d6/0',
      '1d6/-0',
      '10/+0',
      '1d20/(5-5)',
      'dddd',
      'invalid',
      'hello world',
      '2x6',
      '2d',
      'd',
      '1d20 5',
      '%',
    ];

    it.each(invalidCases)('rejects invalid expression: %j', (expr) => {
      expect(isValidDiceExpression(expr)).toBe(false);
    });
  });
});
